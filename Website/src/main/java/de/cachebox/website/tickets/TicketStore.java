package de.cachebox.website.tickets;

import de.cachebox.website.tickets.TicketModels.*;
import jakarta.annotation.PreDestroy;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.*;
import java.time.Instant;
import java.util.*;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.security.access.AccessDeniedException;
import org.springframework.stereotype.Service;

/** One embedded database, with authorization enforced before reading ticket content or attachments. */
@Service
public class TicketStore {
    private final Connection db;
    final Path directory;

    public TicketStore(@Value("${website.tickets.directory:${website.analytics.directory:./data}/tickets}") String directory) throws Exception {
        this.directory = Path.of(directory).toAbsolutePath().normalize();
        Files.createDirectories(this.directory);
        if (Files.getFileStore(this.directory).supportsFileAttributeView("posix")) {
            Files.setPosixFilePermissions(this.directory, java.nio.file.attribute.PosixFilePermissions.fromString("rwx------"));
        }
        db = DriverManager.getConnection("jdbc:h2:file:" + this.directory.resolve("tickets") + ";DB_CLOSE_ON_EXIT=FALSE", "sa", "");
        execute("""
                CREATE TABLE IF NOT EXISTS ticket_users (
                    username VARCHAR(40) PRIMARY KEY, password_hash VARCHAR(100) NOT NULL, created_at BIGINT NOT NULL)
                """);
        execute("""
                CREATE TABLE IF NOT EXISTS tickets (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, uid VARCHAR(36) UNIQUE NOT NULL,
                    owner VARCHAR(40) NOT NULL, title VARCHAR(1024) NOT NULL, body CLOB NOT NULL,
                    kind VARCHAR(20) NOT NULL, status VARCHAR(20) NOT NULL, sort_rank BIGINT NOT NULL,
                    revision BIGINT NOT NULL DEFAULT 0, created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL,
                    github_number BIGINT UNIQUE, share_github BOOLEAN NOT NULL DEFAULT FALSE,
                    from_github BOOLEAN NOT NULL DEFAULT FALSE, conflict BOOLEAN NOT NULL DEFAULT FALSE,
                    base_title VARCHAR(1024), base_body CLOB, base_closed BOOLEAN,
                    remote_title VARCHAR(1024), remote_body CLOB, remote_closed BOOLEAN)
                """);
        execute("""
                CREATE TABLE IF NOT EXISTS ticket_messages (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, uid VARCHAR(36) UNIQUE NOT NULL,
                    ticket_id BIGINT NOT NULL REFERENCES tickets(id), author VARCHAR(100) NOT NULL,
                    body CLOB NOT NULL, internal BOOLEAN NOT NULL, created_at BIGINT NOT NULL,
                    github_id BIGINT UNIQUE, github_body CLOB)
                """);
        execute("""
                CREATE TABLE IF NOT EXISTS ticket_attachments (
                    id VARCHAR(36) PRIMARY KEY, ticket_id BIGINT NOT NULL REFERENCES tickets(id),
                    name VARCHAR(200) NOT NULL, media_type VARCHAR(30) NOT NULL, byte_size BIGINT NOT NULL,
                    image_data BLOB NOT NULL)
                """);
        execute("CREATE INDEX IF NOT EXISTS ticket_owner_idx ON tickets(owner)");
        execute("CREATE INDEX IF NOT EXISTS ticket_message_idx ON ticket_messages(ticket_id)");
    }

    public synchronized boolean userExists(String username) {
        return sql(() -> !query("SELECT username FROM ticket_users WHERE username=?", r -> r.getString(1), username).isEmpty());
    }

    public synchronized String passwordHash(String username) {
        return sql(() -> query("SELECT password_hash FROM ticket_users WHERE username=?", r -> r.getString(1), username).stream().findFirst().orElse(null));
    }

    public synchronized void register(String username, String hash) {
        sql(() -> {
            if (userExists(username)) throw new TicketException("Dieser Benutzername ist bereits vergeben.");
            execute("INSERT INTO ticket_users VALUES (?, ?, ?)", username, hash, now());
            return null;
        });
    }

    public synchronized Ticket create(Actor actor, String title, String body, Kind kind, boolean shareGithub) {
        validateText(title, body);
        Objects.requireNonNull(kind);
        return sql(() -> {
            long count = query("SELECT COUNT(*) FROM tickets WHERE owner=? AND created_at>?", r -> r.getLong(1),
                    actor.username(), now() - 86400000L).getFirst();
            if (!actor.admin() && count >= 20) throw new TicketException("Du hast heute bereits 20 Tickets erstellt. Bitte morgen erneut versuchen.");
            long id = insert("""
                    INSERT INTO tickets(uid, owner, title, body, kind, status, sort_rank, created_at, updated_at, share_github)
                    VALUES (?, ?, ?, ?, ?, 'NEW', ?, ?, ?, ?)
                    """, UUID.randomUUID().toString(), actor.username(), title.strip(), body.strip(), kind.name(), nextRank(), now(), now(), shareGithub);
            return get(actor, id);
        });
    }

    public synchronized List<Ticket> list(Actor actor) {
        return sql(() -> actor.admin()
                ? query("SELECT * FROM tickets ORDER BY sort_rank, id", this::ticket)
                : query("SELECT * FROM tickets WHERE owner=? ORDER BY updated_at DESC, id DESC", this::ticket, actor.username()));
    }

    public synchronized Ticket get(Actor actor, long id) {
        Ticket ticket = sql(() -> query("SELECT * FROM tickets WHERE id=?", this::ticket, id).stream().findFirst()
                .orElseThrow(() -> new AccessDeniedException("Ticket nicht verfügbar.")));
        if (!actor.admin() && !actor.username().equals(ticket.owner())) throw new AccessDeniedException("Ticket nicht verfügbar.");
        return ticket;
    }

    public synchronized void edit(Actor actor, long id, long revision, String title, String body, Kind kind) {
        get(actor, id);
        validateText(title, body);
        sql(() -> {
            if (execute("UPDATE tickets SET title=?, body=?, kind=?, revision=revision+1, updated_at=? WHERE id=? AND revision=?",
                    title.strip(), body.strip(), Objects.requireNonNull(kind).name(), now(), id, revision) != 1) {
                throw new TicketException("Das Ticket wurde inzwischen geändert. Bitte neu laden und die Änderungen erneut übernehmen.");
            }
            return null;
        });
    }

    public synchronized void status(Actor actor, long id, Status status) {
        actor.requireAdmin();
        get(actor, id);
        sql(() -> { execute("UPDATE tickets SET status=?, revision=revision+1, updated_at=? WHERE id=?", status.name(), now(), id); return null; });
    }

    public synchronized void allowGithub(Actor actor, long id) {
        if (!get(actor, id).owner().equals(actor.username())) throw new AccessDeniedException("Nur der Ersteller kann die Veröffentlichung freigeben.");
        sql(() -> { execute("UPDATE tickets SET share_github=TRUE, revision=revision+1 WHERE id=?", id); return null; });
    }

    public synchronized List<Message> messages(Actor actor, long id) {
        get(actor, id);
        return sql(() -> query("SELECT * FROM ticket_messages WHERE ticket_id=?" + (actor.admin() ? "" : " AND internal=FALSE")
                + " ORDER BY created_at, id", this::message, id));
    }

    public synchronized void reply(Actor actor, long id, String body, boolean internal) {
        get(actor, id);
        if (internal) actor.requireAdmin();
        requireLength(body, 1, 20000, "Bitte einen Text mit höchstens 20.000 Zeichen eingeben.");
        sql(() -> transaction(() -> {
            insert("INSERT INTO ticket_messages(uid, ticket_id, author, body, internal, created_at) VALUES (?, ?, ?, ?, ?, ?)",
                    UUID.randomUUID().toString(), id, actor.username(), body.strip(), internal, now());
            execute("UPDATE tickets SET updated_at=? WHERE id=?", now(), id);
            return null;
        }));
    }

    /** Move against the full persisted list, even when the UI currently filters it. */
    public synchronized void move(Actor actor, long moving, long target, boolean before) {
        actor.requireAdmin();
        if (moving == target) return;
        sql(() -> transaction(() -> {
            List<Long> ids = new ArrayList<>(query("SELECT id FROM tickets ORDER BY sort_rank, id", r -> r.getLong(1)));
            if (!ids.remove(moving) || !ids.contains(target)) throw new TicketException("Die Reihenfolge hat sich geändert. Bitte aktualisieren.");
            ids.add(ids.indexOf(target) + (before ? 0 : 1), moving);
            for (int i = 0; i < ids.size(); i++) execute("UPDATE tickets SET sort_rank=? WHERE id=?", i + 1L, ids.get(i));
            return null;
        }));
    }

    public synchronized List<Attachment> attachments(Actor actor, long ticketId) {
        get(actor, ticketId);
        return sql(() -> query("SELECT id, ticket_id, name, media_type, byte_size FROM ticket_attachments WHERE ticket_id=? ORDER BY id",
                this::attachment, ticketId));
    }

    public synchronized void attach(Actor actor, long ticketId, String name, String type, byte[] image) {
        get(actor, ticketId);
        sql(() -> {
            if (attachments(actor, ticketId).size() >= 10) throw new TicketException("Je Ticket sind höchstens zehn Screenshots möglich.");
            execute("INSERT INTO ticket_attachments VALUES (?, ?, ?, ?, ?, ?)", UUID.randomUUID().toString(), ticketId, name, type, image.length, image);
            return null;
        });
    }

    public synchronized Attachment attachment(Actor actor, String id) {
        Attachment file = sql(() -> query("SELECT id, ticket_id, name, media_type, byte_size FROM ticket_attachments WHERE id=?", this::attachment, id)
                .stream().findFirst().orElseThrow(() -> new AccessDeniedException("Screenshot nicht verfügbar.")));
        get(actor, file.ticketId());
        return file;
    }

    public synchronized byte[] image(Actor actor, String id) {
        attachment(actor, id);
        return sql(() -> query("SELECT image_data FROM ticket_attachments WHERE id=?", r -> r.getBytes(1), id).getFirst());
    }

    // Package-private synchronization API: never expose notes through these methods.
    synchronized List<SyncState> syncTickets() {
        return sql(() -> query("SELECT * FROM tickets WHERE share_github=TRUE ORDER BY id", this::syncState));
    }

    synchronized Ticket importIssue(long number, String title, String body, boolean closed, Kind kind) {
        return sql(() -> {
            var existing = query("SELECT * FROM tickets WHERE github_number=?", this::ticket, number);
            if (!existing.isEmpty()) return existing.getFirst();
            long id = insert("""
                    INSERT INTO tickets(uid,owner,title,body,kind,status,sort_rank,created_at,updated_at,github_number,
                    share_github,from_github,base_title,base_body,base_closed) VALUES (?, '', ?, ?, ?, ?, ?, ?, ?, ?, TRUE, TRUE, ?, ?, ?)
                    """, UUID.randomUUID().toString(), title, body, kind.name(), (closed ? Status.DONE : Status.NEW).name(),
                    nextRank(), now(), now(), number, title, body, closed);
            return query("SELECT * FROM tickets WHERE id=?", this::ticket, id).getFirst();
        });
    }

    synchronized void link(long id, long number) {
        sql(() -> { execute("UPDATE tickets SET github_number=? WHERE id=? AND github_number IS NULL", number, id); return null; });
    }

    synchronized void acknowledge(Ticket snapshot, String title, String body, boolean closed, String localBody, boolean applyRemote) {
        sql(() -> transaction(() -> {
            Ticket current = query("SELECT * FROM tickets WHERE id=?", this::ticket, snapshot.id()).getFirst();
            if (applyRemote && current.revision() != snapshot.revision()) {
                conflict(snapshot.id(), title, body, closed);
                return null;
            }
            if (applyRemote) {
                Status status = closed ? Status.DONE : (current.status().closed() ? Status.NEW : current.status());
                execute("UPDATE tickets SET title=?,body=?,status=?,revision=revision+1,updated_at=? WHERE id=?",
                        title, localBody, status.name(), now(), snapshot.id());
            }
            execute("UPDATE tickets SET base_title=?,base_body=?,base_closed=?,conflict=FALSE,remote_title=NULL,remote_body=NULL,remote_closed=NULL WHERE id=?",
                    title, body, closed, snapshot.id());
            return null;
        }));
    }

    synchronized void conflict(long id, String title, String body, boolean closed) {
        sql(() -> { execute("UPDATE tickets SET conflict=TRUE,remote_title=?,remote_body=?,remote_closed=? WHERE id=?", title, body, closed, id); return null; });
    }

    public synchronized Conflict conflictDetails(Actor actor, long id) {
        actor.requireAdmin();
        return sql(() -> query("SELECT remote_title, remote_body, remote_closed FROM tickets WHERE id=? AND conflict=TRUE",
                r -> new Conflict(r.getString(1), r.getString(2), r.getBoolean(3)), id).stream().findFirst().orElse(null));
    }

    public synchronized void resolve(Actor actor, long id, boolean useGithub, long expectedRevision, String expectedRemoteBody) {
        actor.requireAdmin();
        sql(() -> transaction(() -> {
            SyncState state = query("SELECT * FROM tickets WHERE id=?", this::syncState, id).getFirst();
            if (!state.ticket().conflict() || state.remoteTitle() == null) throw new TicketException("Kein offener Synchronisationskonflikt.");
            if (state.ticket().revision() != expectedRevision || !Objects.equals(state.remoteBody(), expectedRemoteBody)) {
                throw new TicketException("Der Konflikt hat sich inzwischen geändert. Bitte neu laden und erneut prüfen.");
            }
            if (useGithub) {
                Status status = state.remoteClosed() ? Status.DONE : (state.ticket().status().closed() ? Status.NEW : state.ticket().status());
                execute("UPDATE tickets SET title=?,body=?,status=?,revision=revision+1,updated_at=? WHERE id=?",
                        state.remoteTitle(), GithubTicketSync.localBody(state.ticket(), state.remoteBody()), status.name(), now(), id);
            }
            execute("UPDATE tickets SET base_title=?,base_body=?,base_closed=?,conflict=FALSE WHERE id=?",
                    state.remoteTitle(), state.remoteBody(), state.remoteClosed(), id);
            return null;
        }));
    }

    synchronized List<Message> syncMessages(long id) {
        return sql(() -> query("SELECT * FROM ticket_messages WHERE ticket_id=? AND internal=FALSE ORDER BY id", this::message, id));
    }

    synchronized void linkMessage(long id, long githubId, String body) {
        sql(() -> { execute("UPDATE ticket_messages SET github_id=?,github_body=NULL WHERE id=? AND internal=FALSE", githubId, id); return null; });
    }

    synchronized void importComment(long ticketId, long githubId, String author, String body, String displayBody, Instant createdAt) {
        sql(() -> {
            var existing = query("SELECT * FROM ticket_messages WHERE github_id=?", this::message, githubId);
            if (existing.isEmpty()) {
                insert("INSERT INTO ticket_messages(uid,ticket_id,author,body,internal,created_at,github_id,github_body) VALUES (?,?,?,?,FALSE,?,?,?)",
                        UUID.randomUUID().toString(), ticketId, "GitHub: " + author, displayBody, createdAt.toEpochMilli(), githubId, body);
            } else if (!Objects.equals(existing.getFirst().githubBody(), body)) {
                execute("UPDATE ticket_messages SET body=?,github_body=? WHERE id=?", displayBody, body, existing.getFirst().id());
            }
            return null;
        });
    }

    private long nextRank() throws SQLException { return query("SELECT COALESCE(MAX(sort_rank),0)+1 FROM tickets", r -> r.getLong(1)).getFirst(); }
    private static long now() { return System.currentTimeMillis(); }
    static void validateText(String title, String body) {
        requireLength(title, 3, 200, "Der Titel muss 3 bis 200 Zeichen enthalten.");
        requireLength(body, 10, 20000, "Die Beschreibung muss 10 bis 20.000 Zeichen enthalten.");
    }
    static void requireLength(String value, int min, int max, String message) {
        if (value == null || value.strip().length() < min || value.strip().length() > max) throw new TicketException(message);
    }
    private Ticket ticket(ResultSet r) throws SQLException {
        return new Ticket(r.getLong("id"), r.getString("uid"), r.getString("owner"), r.getString("title"), r.getString("body"),
                Kind.valueOf(r.getString("kind")), Status.valueOf(r.getString("status")), r.getLong("sort_rank"), r.getLong("revision"),
                Instant.ofEpochMilli(r.getLong("created_at")), Instant.ofEpochMilli(r.getLong("updated_at")), r.getLong("github_number"),
                r.getBoolean("share_github"), r.getBoolean("conflict"), r.getBoolean("from_github"));
    }
    private SyncState syncState(ResultSet r) throws SQLException {
        return new SyncState(ticket(r), r.getString("base_title"), r.getString("base_body"), (Boolean) r.getObject("base_closed"),
                r.getString("remote_title"), r.getString("remote_body"), (Boolean) r.getObject("remote_closed"));
    }
    private Message message(ResultSet r) throws SQLException {
        return new Message(r.getLong("id"),r.getString("uid"),r.getLong("ticket_id"),r.getString("author"),r.getString("body"),
                r.getBoolean("internal"),Instant.ofEpochMilli(r.getLong("created_at")),r.getLong("github_id"),r.getString("github_body"));
    }
    private Attachment attachment(ResultSet r) throws SQLException {
        return new Attachment(r.getString("id"),r.getLong("ticket_id"),r.getString("name"),r.getString("media_type"),r.getLong("byte_size"));
    }
    private int execute(String statement, Object... values) throws SQLException {
        try (var s = db.prepareStatement(statement)) { bind(s, values); return s.executeUpdate(); }
    }
    private long insert(String statement, Object... values) throws SQLException {
        try (var s = db.prepareStatement(statement, Statement.RETURN_GENERATED_KEYS)) {
            bind(s, values); s.executeUpdate(); try (var keys = s.getGeneratedKeys()) { keys.next(); return keys.getLong(1); }
        }
    }
    private <T> List<T> query(String statement, Row<T> row, Object... values) throws SQLException {
        try (var s = db.prepareStatement(statement)) {
            bind(s, values); try (var r = s.executeQuery()) { List<T> result = new ArrayList<>(); while (r.next()) result.add(row.read(r)); return result; }
        }
    }
    private static void bind(PreparedStatement s, Object... values) throws SQLException { for (int i=0; i<values.length; i++) s.setObject(i+1, values[i]); }
    private <T> T transaction(Sql<T> work) throws SQLException {
        db.setAutoCommit(false);
        try { T result = work.run(); db.commit(); return result; }
        catch (SQLException | RuntimeException ex) { db.rollback(); throw ex; }
        finally { db.setAutoCommit(true); }
    }
    private <T> T sql(Sql<T> work) {
        try { return work.run(); }
        catch (SQLException ex) {
            LoggerFactory.getLogger(getClass()).error("Ticketdatenbank nicht verfügbar (SQLState {}).", ex.getSQLState());
            throw new TicketException("Die Ticketdaten konnten nicht gespeichert oder geladen werden. Bitte erneut versuchen.");
        }
    }
    @FunctionalInterface private interface Sql<T> { T run() throws SQLException; }
    @FunctionalInterface private interface Row<T> { T read(ResultSet row) throws SQLException; }
    @PreDestroy public synchronized void close() throws SQLException { db.close(); }
}
